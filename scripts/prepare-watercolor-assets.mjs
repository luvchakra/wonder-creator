#!/usr/bin/env node
/**
 * Publishes the owner-supplied watercolor artwork (UI redesign §44/§46) as responsive, content-hashed AVIF + WebP files
 * and writes the typed registry `packages/ui/src/brand/watercolor.ts`. The artwork is never redrawn or recoloured: each
 * source is only trimmed to its opaque bounds (transparent padding) and downscaled — never upscaled.
 *
 *   node scripts/prepare-watercolor-assets.mjs <dir with the 5000px PNG sources>
 *
 * Sources aren't committed (≈5000px each); see packages/ui/src/brand/ASSETS.md for provenance.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const sharp = createRequire(join(root, "apps/web/package.json"))("sharp");
const src = process.argv[2];
if (!src) throw new Error("usage: prepare-watercolor-assets.mjs <source dir>");

const WIDTHS = [430, 768, 1024, 1440, 1920];
const ASSETS = [
  { key: "paletteMotif", file: "watercolor-paint-palette.png", widths: [96, 144, 192, 430, 768] },
  { key: "cornerTopLeft", file: "floral-corner-top-left.png" },
  { key: "cornerTopRight", file: "floral-corner-top-right.png" },
  { key: "cornerBottomLeft", file: "floral-corner-bottom-left.png" },
  { key: "cornerBottomRight", file: "floral-corner-bottom-right.png" },
  { key: "peachWash", file: "watercolor-peach-wash.png" },
];

const out = join(root, "apps/web/public/brand/watercolor");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const registry = {};
for (const a of ASSETS) {
  const trimmed = await sharp(join(src, a.file)).trim({ threshold: 0, lineArt: false }).png().toBuffer({ resolveWithObject: true });
  const { width, height } = trimmed.info;
  const name = a.file.replace(/\.png$/, "");
  const widths = [...new Set((a.widths ?? WIDTHS).map((w) => Math.min(w, width)))];
  const variants = { avif: [], webp: [] };
  for (const w of widths) {
    const img = sharp(trimmed.data).resize({ width: w, withoutEnlargement: true });
    for (const [fmt, buf] of [
      ["avif", await img.clone().avif({ quality: 55, effort: 6 }).toBuffer()],
      ["webp", await img.clone().webp({ quality: 78, alphaQuality: 90, effort: 6 }).toBuffer()],
    ]) {
      const hash = createHash("sha256").update(buf).digest("hex").slice(0, 10);
      const f = `${name}-${w}.${hash}.${fmt}`;
      writeFileSync(join(out, f), buf);
      variants[fmt].push({ src: `/brand/watercolor/${f}`, width: w });
    }
  }
  registry[a.key] = { width, height, ...variants };
  console.log(a.key, `${width}x${height}`, widths.join(","));
}

const ts = `// Generated by scripts/prepare-watercolor-assets.mjs — do not edit by hand.
// Owner-supplied watercolor artwork (see ASSETS.md). Files are content-hashed and served immutable.

export interface BrandImageVariant {
  src: string;
  width: number;
}

export interface BrandImage {
  /** Intrinsic size of the largest published rendition's source (trimmed original). */
  width: number;
  height: number;
  avif: readonly BrandImageVariant[];
  webp: readonly BrandImageVariant[];
}

export const WATERCOLOR = ${JSON.stringify(registry, null, 2)} as const satisfies Record<string, BrandImage>;

export type WatercolorKey = keyof typeof WATERCOLOR;
`;
const target = join(root, "packages/ui/src/brand/watercolor.ts");
writeFileSync(target, ts);
execFileSync("npx", ["prettier", "--write", "--print-width", "200", target], { cwd: root, stdio: "ignore" });
console.log("files:", readdirSync(out).length);
