#!/usr/bin/env node
/**
 * Home-screen icons from the Vector Kit's own app icon (owner, 4 Oct 2026: "installed app shows white lines in the
 * border, also the image quality is poor, make it better and bigger").
 *
 *   node scripts/prepare-app-icons.mjs
 *
 * Android and iOS cut their own shape out of a home-screen icon. An icon with its own rounded corners gets shrunk onto a
 * white plate (the white rim) and blurred. These are the same mark, colours and gradient — nothing redrawn — rendered
 * sharp from the vector at full size, full-bleed (square, no rounded corners or outline, the platform rounds it), with
 * the mark 5% larger and still inside the 80% maskable safe circle. Writes content-hashed PNGs and
 * `packages/ui/src/brand/app-icons.ts`.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const sharp = createRequire(join(root, "apps/web/package.json"))("sharp");
const dir = join(root, "apps/web/public/brand/kit");
const src = readdirSync(dir).find((f) => /^app-icon-primary\.[0-9a-f]{10}\.svg$/.test(f));
if (!src) throw new Error("app-icon-primary SVG not found");
const svg = readFileSync(join(dir, src), "utf8");

// Full bleed: the background fills the square (no corner radius), the faint outline goes, the mark grows 5% about the centre.
const bleed = svg
  .replace('<rect width="1024" height="1024" rx="230.4" fill="url(#bg)"/>', '<rect width="1024" height="1024" fill="url(#bg)"/>')
  .replace(/<rect x="1\.5" y="1\.5"[^>]*\/>/, "")
  .replace('<g transform="translate(163.84 167.12) scale(3.48160)">', '<g transform="translate(512 512) scale(1.05) translate(-512 -512) translate(163.84 167.12) scale(3.48160)">');
if (bleed === svg || /rx="230\.4"/.test(bleed)) throw new Error("app icon SVG changed shape; update this script");

const hash = (buf) => createHash("sha256").update(buf).digest("hex").slice(0, 10);
const out = {};
for (const [key, size] of [["maskable512", 512], ["maskable192", 192], ["apple180", 180]]) {
  // Rendered at 4× density from the vector, then downscaled: crisp edges at every size.
  const buf = await sharp(Buffer.from(bleed), { density: 288 }).resize(size, size).flatten({ background: "#ffffff" }).png({ compressionLevel: 9 }).toBuffer();
  const name = `app-icon-full-${size}.${hash(buf)}.png`;
  writeFileSync(join(dir, name), buf);
  out[key] = { src: `/brand/kit/${name}`, width: size, height: size };
}
writeFileSync(
  join(root, "packages/ui/src/brand/app-icons.ts"),
  `// Generated by scripts/prepare-app-icons.mjs from the Vector Kit's app icon — full-bleed home-screen icons. Do not edit.\nexport const APP_ICONS = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(out);
